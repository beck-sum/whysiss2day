document.addEventListener("click", (e) => {
  const option = e.target.closest(optionItem);
  const trigger = e.target.closest(selectTrigger);
 
  if (trigger) {
    toggleSelect();
    return;
  }
 
  if (option) {
    selectOption(option);
    return;
  }
 
  if (document.querySelector(containerOptions).classList.contains("open")) {
    toggleSelect();
  }
  if (e.target.closest(randomizerButton)) {
    generationRandomPhrase();
  }
});
function toggleSelect() {
  let select = document.querySelector(containerOptions);
  select.classList.toggle("open");
}
 
function selectOption(option) {
  const selectTriggerElement = document.querySelector(selectTrigger);
 
  selectTriggerElement.dataset.value = option.dataset.value;
  const copyOption = option.cloneNode(true);
  const span = copyOption.querySelector("span");
  if (span) {
    copyOption.removeChild(span);
  }
  selectTriggerElement.innerHTML =
    copyOption.innerHTML +
    `<span class="material-symbols-outlined icon">arrow_drop_down</span>`;
  toggleSelect();
}
 
function isOptionSelectioned() {
  const selectTriggerElement = document.querySelector(selectTrigger);
  return selectTriggerElement.dataset.value !== "notselectioned";
}

function generationRandomPhrase() {
  if (!isOptionSelectioned()) {
    alert("Selecione uma opção antes de gerar a frase!");
    return;
  }
  const numberRandom = Math.floor(Math.random() * daysPhrases.length);
  const phrase = daysPhrases[numberRandom];
  const h2SubtitleElement = document.querySelector(h2Subtitle);
  h2SubtitleElement.classList.add("show");
  h2SubtitleElement.innerHTML = phrase;
}